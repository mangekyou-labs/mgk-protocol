'use strict';
// Deterministic declaration output for the portable JavaScript contract.
const fs = require('node:fs');
const path = require('node:path');
const layouts = require('./program-layouts.json');
const {instructions} = require('./instructions.js');
function typeOf(type) {
 const array = /^\[(.+); (\d+)\]$/.exec(type);
 if (array) return `${typeOf(array[1])}[]`;
 if (type === 'pubkey') return 'Uint8Array';
 if (layouts[type]) return type;
 if (type === 'bool') return 'boolean';
 return ['u64','i64','u128','i128'].includes(type) ? 'bigint' : 'number';
}
let accounts = '// Generated by generate-types.js from the Rust contract; do not edit.\n';
for (const [name,layout] of Object.entries(layouts)) {
 accounts += `export interface ${name} {\n`;
 for (const [key,[,type]] of Object.entries(layout.fields)) accounts += ` ${key}: ${typeOf(type)};\n`;
 accounts += '}\n';
}
accounts += 'export interface Accounts {\n';
for (const name of Object.keys(layouts)) accounts += ` ${name}: ${name};\n`;
accounts += `}
export const layouts: Record<keyof Accounts, {size:number; discriminator:number|null; version:number|null; fields: Record<string,[number,string]>; fixture:number[]}>;
export function decodeAccount<N extends keyof Accounts>(name:N,data:Uint8Array):Accounts[N];
export function decodeStruct<N extends keyof Accounts>(name:N,data:Uint8Array,offset?:number):Accounts[N];
export interface Fill {user:Uint8Array; orderId:bigint;qty:bigint;price:bigint;isMaker:boolean;auction:number}
export interface Results {batchId:bigint;spent:boolean;bidClearingPrice:bigint;askClearingPrice:bigint;matchedBidQty:bigint;matchedAskQty:bigint;numFills:number;fills:Fill[]}
export function decodeResults(data:Uint8Array): Results;
export const resultsLayout:{headerSize:number;fillSize:number;fixture:number[]};
`;
let instructionTypes = '// Generated by generate-types.js; do not edit.\nexport const instructions: {\n';
for (const [program,table] of Object.entries(instructions)) {
 instructionTypes += ` ${program}: {\n`;
 for (const [name,spec] of Object.entries(table)) instructionTypes += `  ${name}: {disc:${spec.disc}; fields:[string,string][]; enabled:boolean};\n`;
 instructionTypes += ' };\n';
}
instructionTypes += "};\nexport function encodeInstruction(program:'core'|'matcher'|'oracle',name:string,params?:Record<string,unknown>):Uint8Array;\n";
for (const [name,text] of [['index.d.ts',accounts],['instructions.d.ts',instructionTypes]]) {
 const file = path.join(__dirname,name);
 if (process.argv.includes('--check')) {
  if (fs.readFileSync(file,'utf8') !== text) throw new Error(`Stale declaration: ${name}`);
 } else fs.writeFileSync(file,text);
}
